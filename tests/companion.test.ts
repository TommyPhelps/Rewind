test("modding profiles: create, edit, reorder, notes, checklist, runs, delete", async () => {
  const repo = await setup();
  const skyrim = (await repo.loadGames()).find((g) => g.title === "The Elder Scrolls V: Skyrim")!;
  const id = await repo.createModProfile({ name: "Survival run", gameKey: "skyrim_le", gameId: skyrim.id, manager: "Mod Organizer 2", checklist: presetById("skyrim_le").checklist, entries: parseModList("+SkyUI\n+Frostfall\n-Wet and Cold").mods });
  let p = (await repo.loadModProfiles()).find((x) => x.id === id)!;
  assert.equal(p.entries.length, 3);
  assert.equal(p.entries[2].enabled, false);
  assert.equal(p.checklist.length, presetById("skyrim_le").checklist.length);
  await repo.reorderModEntries(id, [p.entries[2].id, p.entries[0].id, p.entries[1].id]);
  await repo.updateModEntry(p.entries[2].id, { enabled: true, notes: "needs Campfire" });
  await repo.addModEntries(id, [{ name: "Campfire", url: "https://www.nexusmods.com/skyrim/mods/64798" }]);
  await repo.saveModNote({ profileId: id, kind: "compat", title: "Frostfall needs Campfire", body: "Read on the mod page", mods: ["Frostfall", "Campfire"], sourceUrl: "https://www.nexusmods.com/skyrim/mods/11163" });
  await repo.setCheckDone(p.checklist[0].id, true);
  await repo.saveModRun({ profileId: id, name: "Nord ranger", startedAt: "2026-10-01" });
  await repo.updateModProfile(id, { status: "active", gameVersion: "1.9.32" });
  p = (await repo.loadModProfiles()).find((x) => x.id === id)!;
  assert.deepEqual(p.entries.map((e) => e.name), ["Wet and Cold", "SkyUI", "Frostfall", "Campfire"]);
  assert.equal(p.entries[0].enabled, true);
  assert.equal(p.modNotes[0].mods.length, 2);
  assert.ok(p.checklist[0].doneAt);
  assert.equal(p.runs[0].name, "Nord ranger");
  assert.equal(p.status, "active");
  const md = exportModList({ ...p, gameTitle: skyrim.title });
  assert.match(md, /\| 1 \| ✓ \| Wet and Cold \|/);
  await repo.resetChecklist(id);
  assert.ok((await repo.loadModProfiles())[0].checklist.every((c) => !c.doneAt));
  // Deleting the game keeps the profile (it just loses the link).
  await repo.deleteGames([skyrim.id]);
  p = (await repo.loadModProfiles()).find((x) => x.id === id)!;
  assert.equal(p.gameId, null);
  await repo.deleteModProfile(id);
  assert.equal((await repo.loadModProfiles()).length, 0);
  const left = await repo.driver.select<{ n: number }>(`SELECT (SELECT COUNT(*) FROM mod_entries) + (SELECT COUNT(*) FROM mod_notes) + (SELECT COUNT(*) FROM mod_checklist) + (SELECT COUNT(*) FROM mod_runs) AS n`);
  assert.equal(Number(left[0].n), 0, "children removed with the profile");
});

test("upgrade from schema v3 keeps everything and adds the Phase 4 tables", async () => {
  const db = nodeDriver();
  await db.execute(`CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL)`);
  for (const m of MIGRATIONS.filter((x) => x.version <= 3)) await db.batch([...m.sql.map((sql) => ({ sql })), { sql: `INSERT INTO meta (key, value) VALUES ('schema_version', ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value`, params: [String(m.version)] }]);
  await db.execute(`INSERT INTO games (id, title, canon, notes, rating, status, created_at, updated_at) VALUES ('g1', 'Kenshi', 'kenshi', 'keep me', 4, 'paused', '2026-01-01', '2026-01-01')`);
  await db.execute(`INSERT INTO secrets (key, value) VALUES ('steam_api_key', 'abc')`);
  const repo = new Repo(db);
  const applied = await repo.init();
  assert.deepEqual(applied, [4]);
  const g = (await repo.loadGames())[0];
  assert.equal(g.notes, "keep me");
  assert.equal(g.rating, 4);
  assert.equal(g.status, "paused");
  assert.equal(await repo.getSecret("steam_api_key"), "abc");
  await repo.setMark({ key: gameKey("g1"), kind: "want", title: "Kenshi", gameId: "g1" });
  assert.equal((await repo.loadMarks()).length, 1);
});

test("backup round trip includes answers and modding profiles; merge keeps yours", async () => {
  const repo = await setup();
  const games = await repo.loadGames();
  const k = games.find((g) => g.title.startsWith("Kenshi"))!;
  await repo.setMark({ key: gameKey(k.id), kind: "not_interested", title: k.title, gameId: k.id });
  await repo.setMark({ key: igdbKey(2001), kind: "wishlist", title: "Ashen Crown (TEST)", snapshot: { year: 2005 } });
  await repo.setMark({ key: modrinthKey("p_lantern"), kind: "want", title: "Lantern Valley (TEST)", snapshot: { title: "Lantern Valley (TEST)" } });
  const pid = await repo.createModProfile({ name: "Main", gameKey: "minecraft", gameTitle: "Minecraft", packKey: modrinthKey("p_lantern"), checklist: ["Back up saves"], entries: [{ name: "Sodium" }] });
  const backup = await createBackup(repo, "4.0.0");
  for (const t of BACKUP_TABLES) assert.ok(Array.isArray(backup.data[t]), t);
  assert.equal(backup.data.discover_marks.length, 3);
  assert.equal(backup.data.mod_profiles.length, 1);
  assert.ok(!JSON.stringify(backup).includes("steam_api_key"), "secrets never in backups");
  const v = validateBackup(JSON.parse(JSON.stringify(backup)));
  assert.ok(v.ok, v.ok ? "" : v.errors.join("; "));

  // Replace into an empty database.
  const fresh = new Repo(nodeDriver());
  await fresh.init();
  await applyRestore(fresh, backup, "replace");
  assert.equal((await fresh.loadMarks()).length, 3);
  const p = (await fresh.loadModProfiles())[0];
  assert.equal(p.name, "Main");
  assert.equal(p.entries[0].name, "Sodium");
  assert.equal(p.checklist.length, 1);

  // Merge: your newer answer wins; nothing duplicates.
  await fresh.setMark({ key: igdbKey(2001), kind: "played", title: "Ashen Crown (TEST)" });
  await applyRestore(fresh, backup, "merge");
  const marks = await fresh.loadMarks();
  assert.equal(marks.length, 3);
  assert.equal(marks.find((m) => m.key === igdbKey(2001))!.kind, "played");
  assert.equal((await fresh.loadModProfiles()).length, 1);
  assert.equal((await fresh.loadModProfiles())[0].entries.length, 1);
  assert.equal(pid, p.id);
});

test("older backups (schema 3) without Phase 4 sections still restore", async () => {
  const repo = await setup();
  const b = await createBackup(repo, "3.0.0");
  const old = JSON.parse(JSON.stringify(b));
  old.schemaVersion = 3;
  for (const t of ["discover_marks", "mod_profiles", "mod_entries", "mod_notes", "mod_checklist", "mod_runs"]) delete old.data[t];
  const v = validateBackup(old);
  assert.ok(v.ok);
  if (v.ok) assert.ok(!v.warnings.some((w) => /discover_marks|mod_profiles/.test(w)), "no warnings for sections that didn't exist yet");
  const fresh = new Repo(nodeDriver());
  await fresh.init();
  if (v.ok) await applyRestore(fresh, v.backup, "replace");
  assert.equal((await fresh.loadGames()).length, (await repo.loadGames()).length);
});
