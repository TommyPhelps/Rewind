test("mod list import: MO2 modlist.txt, plugins.txt, links and plain lines", () => {
  const mo2 = parseModList("# This file was automatically generated by Mod Organizer.\n+SkyUI\n-Immersive Armors\n*DLC: Dawnguard\n+Unofficial Skyrim Special Edition Patch\n+Gameplay_separator\n");
  assert.equal(mo2.format, "mo2");
  assert.deepEqual(mo2.mods.map((m) => [m.name, m.enabled]), [["SkyUI", true], ["Immersive Armors", false], ["Unofficial Skyrim Special Edition Patch", true]]);
  assert.equal(mo2.skipped, 2);
  const plugins = parseModList("*Unofficial Skyrim Special Edition Patch.esp\nSkyUI_SE.esp\n*Alternate Start - Live Another Life.esp\n");
  assert.equal(plugins.format, "plugins");
  assert.deepEqual(plugins.mods.map((m) => m.enabled), [true, false, true]);
  const links = parseModList("SkyUI - https://www.nexusmods.com/skyrimspecialedition/mods/12604\nhttps://modrinth.com/mod/sodium\nhttps://www.curseforge.com/minecraft/mc-mods/jei\njavascript:alert(1)\nhttps://modrinth.com/mod/sodium");
  assert.equal(links.format, "links");
  assert.deepEqual(links.mods.map((m) => m.name), ["SkyUI", "Sodium", "Jei", "javascript:alert(1)"]);
  assert.equal(links.mods[0].url, "https://www.nexusmods.com/skyrimspecialedition/mods/12604");
  assert.equal(links.mods[3].url, "", "not a web link: kept as a name only");
  assert.equal(links.skipped, 1, "duplicate link skipped");
  const plain = parseModList("- Create v0.5.1\n- Farmer's Delight 1.2.4\nJourneyMap\n");
  assert.deepEqual(plain.mods.map((m) => [m.name, m.version]), [["Create", "0.5.1"], ["Farmer's Delight", "1.2.4"], ["JourneyMap", ""]]);
});

